"""Generate the exported il2cpp_* trampolines of the proxy libil2cpp.so.

Each export jumps through a slot filled with the matching _il2cpp_* address
inside UnityFramework. A few names are wrapped in C (proxy.c) and get the
`real_` slot only.
usage: python -I tools/gen_api_stubs.py loader/proxy/il2cpp_api.txt <out.S>
"""
import sys

WRAPPED = {"il2cpp_init", "il2cpp_set_data_dir", "il2cpp_set_config_dir", "il2cpp_method_get_param_count", "il2cpp_runtime_invoke", "il2cpp_runtime_invoke_convert_args",
           "il2cpp_add_internal_call"}

names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = ["// generated by tools/gen_api_stubs.py; do not edit", "    .text"]
for n in names:
    sym = f"real_{n}" if n in WRAPPED else n
    out += [f"    .globl {sym}", f"    .type {sym}, %function", f"{sym}:",
            f"    adrp x16, mk_api_slots+{8 * names.index(n)}",
            f"    ldr x16, [x16, :lo12:mk_api_slots+{8 * names.index(n)}]",
            "    br x16"]
out += ["    .data", "    .p2align 3", "    .globl mk_api_slots", "    .hidden mk_api_slots", "mk_api_slots:",
        f"    .zero {8 * len(names)}", "    .section .data.rel.ro, \"aw\"", "    .globl mk_api_names", "    .hidden mk_api_names",
        "mk_api_names:"]
out += [f"    .quad .Lname{i}" for i in range(len(names))] + ["    .quad 0"]
out += [f'.Lname{i}: .asciz "_{n}"' for i, n in enumerate(names)]
open(sys.argv[2], "w").write("\n".join(out) + "\n")
