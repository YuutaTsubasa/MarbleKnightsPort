"""Generate loader/win/ga_stubs.c: a GameAssembly.dll that exports every il2cpp_* API function
(loader/proxy/il2cpp_api.txt) as a logging stub returning 0. First Windows milestone: see what the
official UnityPlayer.dll calls before any game code runs.
usage: python -I tools/gen_win_stubs.py loader/proxy/il2cpp_api.txt <out.c>
"""
import sys

names = [l.strip() for l in open(sys.argv[1]) if l.strip()]
out = ["// generated by tools/gen_win_stubs.py; do not edit", "#include <stdint.h>",
       "void mk_ga_log_call(const char *name, int *seen);",
       "#define STUB(n) __declspec(dllexport) uintptr_t n(void) { static int seen; mk_ga_log_call(#n, &seen); return 0; }"]
out += [f"STUB({n})" for n in names]
open(sys.argv[2], "w", newline="\n").write("\n".join(out) + "\n")
