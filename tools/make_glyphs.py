"""Draw simple Xbox-style controller button icons and emit them as a C include.

The game shows controller glyphs by loading a PNG whose path the AppleGameController plugin
returns (on iOS: a rendered SF Symbol). These are our own drawings: white shapes with a soft
dark edge so they read on both light and dark UI.

usage: python -E tools/make_glyphs.py <out.inc>      (needs Pillow)
"""
import io
import os
import sys

from PIL import Image, ImageDraw, ImageFilter, ImageFont

S = 128
WHITE = (255, 255, 255, 255)


def font(size):
    for name in ("arialbd.ttf", "DejaVuSans-Bold.ttf", "seguisb.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            pass
    return ImageFont.load_default()


def finish(img):
    # dark halo behind the white glyph
    alpha = img.split()[3]
    halo = Image.new("RGBA", img.size, (0, 0, 0, 0))
    halo.putalpha(alpha.filter(ImageFilter.MaxFilter(7)).point(lambda a: a * 0.55))
    out = Image.alpha_composite(halo, img)
    buf = io.BytesIO()
    out.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def text_center(d, box, s, size):
    f = font(size)
    l, t, r, b = d.textbbox((0, 0), s, font=f)
    x0, y0, x1, y1 = box
    d.text(((x0 + x1 - (r - l)) / 2 - l, (y0 + y1 - (b - t)) / 2 - t), s, font=f, fill=WHITE)


def circle_letter(letter):
    img = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(img)
    d.ellipse((10, 10, S - 10, S - 10), outline=WHITE, width=9)
    text_center(d, (10, 10, S - 10, S - 10), letter, 64)
    return finish(img)


def bumper(label, top):
    img = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(img)
    box = (8, 30, S - 8, S - 30)
    d.rounded_rectangle(box, radius=26 if top else 14, outline=WHITE, width=8,
                        corners=(top, top, not top, not top) if hasattr(d, "rounded_rectangle") else None)
    text_center(d, box, label, 40)
    return finish(img)


def dpad():
    img = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(img)
    w = 34
    d.rounded_rectangle(((S - w) / 2, 12, (S + w) / 2, S - 12), radius=8, fill=WHITE)
    d.rounded_rectangle((12, (S - w) / 2, S - 12, (S + w) / 2), radius=8, fill=WHITE)
    return finish(img)


def stick(letter):
    img = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(img)
    d.ellipse((12, 12, S - 12, S - 12), outline=WHITE, width=8)
    d.ellipse((32, 32, S - 32, S - 32), outline=WHITE, width=6)
    text_center(d, (32, 32, S - 32, S - 32), letter, 36)
    return finish(img)


def menu():
    img = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(img)
    d.ellipse((10, 10, S - 10, S - 10), outline=WHITE, width=9)
    for y in (44, 64, 84):
        d.rounded_rectangle((38, y - 5, S - 38, y + 5), radius=4, fill=WHITE)
    return finish(img)


def options():
    img = Image.new("RGBA", (S, S))
    d = ImageDraw.Draw(img)
    d.ellipse((10, 10, S - 10, S - 10), outline=WHITE, width=9)
    d.rounded_rectangle((36, 40, 78, 74), radius=5, outline=WHITE, width=6)
    d.rounded_rectangle((52, 56, 94, 90), radius=5, fill=WHITE)
    return finish(img)


GLYPHS = {
    "a.circle": lambda: circle_letter("A"), "b.circle": lambda: circle_letter("B"),
    "x.circle": lambda: circle_letter("X"), "y.circle": lambda: circle_letter("Y"),
    "lb.rectangle.roundedbottom": lambda: bumper("LB", False), "rb.rectangle.roundedbottom": lambda: bumper("RB", False),
    "lt.rectangle.roundedtop": lambda: bumper("LT", True), "rt.rectangle.roundedtop": lambda: bumper("RT", True),
    "dpad": dpad, "l.joystick": lambda: stick("L"), "r.joystick": lambda: stick("R"),
    "line.horizontal.3.circle": menu, "rectangle.fill.on.rectangle.fill.circle": options,
}


def main():
    out = ["// generated by tools/make_glyphs.py; do not edit"]
    table = []
    for i, (name, make) in enumerate(GLYPHS.items()):
        png = make()
        out.append(f"static const unsigned char glyph_{i}[{len(png)}] = {{")
        for k in range(0, len(png), 24):
            out.append("    " + ", ".join(str(b) for b in png[k:k + 24]) + ",")
        out.append("};")
        table.append(f'    {{ "{name}", glyph_{i}, sizeof(glyph_{i}) }},')
    out.append("static const struct { const char *name; const unsigned char *png; unsigned size; } g_glyph_pngs[] = {")
    out += table
    out.append("};")
    os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
    with open(sys.argv[1], "w") as f:
        f.write("\n".join(out) + "\n")
    if len(sys.argv) > 2:  # also dump PNGs for a visual check
        os.makedirs(sys.argv[2], exist_ok=True)
        for name, make in GLYPHS.items():
            open(os.path.join(sys.argv[2], name + ".png"), "wb").write(make())


if __name__ == "__main__":
    main()
