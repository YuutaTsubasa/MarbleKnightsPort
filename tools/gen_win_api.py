"""Generate loader/win build sources for the il2cpp API of GameAssembly.dll (Windows build).

Reads DO_API(ret, name, (args)) from Unity's libil2cpp/il2cpp-api-functions.h and writes, for each
function, an exported x64 wrapper that puts the arguments in guest registers (Apple arm64: integers
and pointers in x0-x7, floating point in v0-v7, each in order) and runs the recompiled `_il2cpp_*`
of UnityFramework. Function-pointer arguments (callbacks from the engine) are turned into
host-callback markers the guest can call. Names in SPECIAL are implemented by hand in win_rt.c
(they get a `real_` wrapper only).
usage: python -I tools/gen_win_api.py <il2cpp-api-functions.h> <out.c>
"""
import re
import sys

SPECIAL = {"il2cpp_add_internal_call", "il2cpp_set_data_dir", "il2cpp_init"}
INTS = {"int": "int32_t", "int32_t": "int32_t", "uint32_t": "uint32_t", "bool": "bool", "char": "char",
        "uint8_t": "uint8_t", "int8_t": "int8_t", "uint16_t": "uint16_t", "int16_t": "int16_t", "Il2CppChar": "uint16_t",
        "size_t": "size_t", "int64_t": "int64_t", "uint64_t": "uint64_t", "uintptr_t": "uintptr_t", "intptr_t": "intptr_t",
        "il2cpp_array_size_t": "uintptr_t", "unsigned int": "uint32_t", "long": "int32_t", "unsigned long": "uint32_t"}
CALLBACK_TYPES = {"il2cpp_register_object_callback", "il2cpp_WorldChangedCallback", "Il2CppProfileFunc",
                  "Il2CppProfileAllocFunc", "Il2CppProfileGCFunc", "Il2CppProfileGCResizeFunc", "Il2CppProfileFileIOFunc",
                  "Il2CppProfileThreadFunc", "Il2CppFrameWalkFunc", "Il2CppLogCallback", "Il2CppSetFindPlugInCallback",
                  "Il2CppBacktraceFunc", "Il2CppAndroidUpStateFunc", "Il2CppMethodPointer", "Il2CppProfileThreadFunc"}


def split_args(s):
    out, depth, cur = [], 0, ""
    for ch in s:
        depth += ch == "("
        depth -= ch == ")"
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return [a for a in out if a and a != "void"]


def classify(t):
    """-> (kind, ctype): kind i (integer register), f/d (float/double register), c (callback)."""
    t = re.sub(r"\bconst\b", "", t).strip()
    if "(*" in t or "( *" in t:
        return "c", "void *"
    base = re.sub(r"\s+\w+$", "", t).strip() if not t.endswith("*") and len(t.split()) > 1 else t
    if "*" in t or "[" in t:
        return "i", "uintptr_t"
    if base in ("float",):
        return "f", "float"
    if base in ("double",):
        return "d", "double"
    if base in CALLBACK_TYPES:
        return "c", "void *"
    if base in INTS:
        return "i", INTS[base]
    if base.startswith("Il2Cpp") or base.startswith("il2cpp"):
        return "i", "int32_t"  # enums
    raise SystemExit(f"unknown type {t!r}")


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    apis = []
    for m in re.finditer(r"^DO_API(?:_NO_RETURN)?\((.*?),\s*(\w+)\s*,\s*\((.*)\)\);", src, re.M):
        ret, name, args = m.group(1).strip(), m.group(2), m.group(3)
        if any(a[1] == name for a in apis):
            continue
        apis.append((ret, name, split_args(args)))
    out = ["// generated by tools/gen_win_api.py from libil2cpp/il2cpp-api-functions.h; do not edit",
           "#include <stdbool.h>", "#include <stdint.h>", "#include <stddef.h>",
           "uint64_t mk_guest_call(int api, const uint64_t *x, int nx, const double *v, int nv, double *fret);",
           "uint64_t mk_host_callback(void *fn, const char *what);",
           "#define EXPORT __declspec(dllexport)"]
    names = []
    for k, (ret, name, args) in enumerate(apis):
        names.append(name)
        rk, rt = ("v", "void") if ret.strip() == "void" else classify(ret)
        params, xs, vs = [], [], []
        for j, a in enumerate(args):
            kind, ct = classify(a)
            params.append(f"{ct} a{j}")
            if kind == "i":
                xs.append(f"(uint64_t)a{j}")
            elif kind == "c" and name in SPECIAL:  # the hand-written entry already made it a marker
                xs.append(f"(uint64_t)(uintptr_t)a{j}")
            elif kind == "c":
                xs.append(f'mk_host_callback(a{j}, "{name}#{j}")')
            elif kind == "f":
                vs.append(f"(double)a{j}" if False else f"mk_f2d(a{j})")
            else:
                vs.append(f"a{j}")
        fn = f"real_{name}" if name in SPECIAL else name
        decl = "" if name in SPECIAL else "EXPORT "
        body = [f"{decl}{rt} {fn}({', '.join(params) or 'void'}) {{"]
        body.append(f"    uint64_t x[] = {{ {', '.join(xs) or '0'} }};")
        body.append(f"    double v[] = {{ {', '.join(vs) or '0'} }};")
        body.append(f"    double fr; uint64_t r = mk_guest_call({k}, x, {len(xs)}, v, {len(vs)}, &fr); (void)r; (void)fr;")
        if rk == "v":
            pass
        elif rk == "f":
            body.append("    return mk_d2f(fr);")
        elif rk == "d":
            body.append("    return fr;")
        else:
            body.append(f"    return ({rt})r;")
        body.append("}")
        out.append("\n".join(body))
    out.insert(7, "// a float travels in the low 32 bits of a v register\n"
               "static inline double mk_f2d(float f) { union { double d; float f[2]; } u = { 0 }; u.f[0] = f; return u.d; }\n"
               "static inline float mk_d2f(double d) { union { double d; float f[2]; } u; u.d = d; return u.f[0]; }")
    out.append("const char *const mk_api_names[] = {\n" + "\n".join(f'    "_{n}",' for n in names) + "\n    0 };")
    out.append(f"const int mk_api_count = {len(names)};")
    open(sys.argv[2], "w", encoding="utf-8", newline="\n").write("\n\n".join(out) + "\n")
    print(f"{len(names)} API wrappers -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
