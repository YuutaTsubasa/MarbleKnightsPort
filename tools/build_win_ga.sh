#!/usr/bin/env bash
# Build the recompiled GameAssembly.dll for the Windows test build and put it, with the prelinked
# image, into work/win/MarbleKnights/. Needs: tools/prelink_win.py and tools/a64toc.py --all
# (work/win/image, work/win/gen), VS 2022 Build Tools, LLVM (clang-cl, lld-link).
# The full compile takes the heavy-build lock. Everything produced is game-derived: work/ only.
# usage: tools/build_win_ga.sh [--runtime-only]   (--runtime-only: reuse the compiled chunks)
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
ops="$USERPROFILE/Data/10_Projects/tailsmachine-ops"
w="$here/work/win"
llvm="/c/Program Files/LLVM/bin"
vcvars='C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat'

# MSVC environment (INCLUDE, LIB) for clang-cl / lld-link
eval "$(cmd //c "set PATH=%PATH%;C:\\Program Files (x86)\\Microsoft Visual Studio\\Installer && call \"$vcvars\" >nul && set" \
  | tr -d '\r' | grep -E '^(INCLUDE|LIB|LIBPATH)=' | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/^\([A-Z]*\)=\(.*\)$/export \1="\2"/')"

python -I "$here/tools/gen_win_api.py" "$here/work/unity/editor/Editor/Data/il2cpp/libil2cpp/il2cpp-api-functions.h" "$w/api_wrappers.c"
python -I - "$w/image/binds.txt" "$w/imports.c" <<'EOF'
import sys
n = sum(1 for _ in open(sys.argv[1], encoding="utf-8"))
with open(sys.argv[2], "w", newline="\n") as f:
    f.write('// generated by tools/build_win_ga.sh: one entry per imported slot (work/win/image/binds.txt)\n#include "win_rt.h"\n')
    f.write("".join(f"void imp_{k}(cpu *c) {{ mk_imp(c, {k}); }}\n" for k in range(n)))
EOF

mkdir -p "$w/obj"
export WIN_CC_INCLUDES="$(cygpath -w "$here/loader/proxy");$(cygpath -w "$here/loader/win")"
export INCLUDE LIB LIBPATH
cc() { for f in "$@"; do WIN_CC_DEBUG=1 bash "$here/tools/win_cc.sh" "$f" "$w/obj"; done; }
if [ "${1:-}" != "--runtime-only" ]; then
  export LOCK_SESSION="${LOCK_SESSION:-marble-knights}" LOCK_MODEL="${LOCK_MODEL:-claude-opus-5-5}"
  "$ops/tools/lock/with-lock.sh" heavy-build 20 "Marble Knights recompiled GameAssembly.dll" --     bash -c "ls '$w/gen'/chunk_*.c | xargs -P $(nproc) -n 1 bash '$here/tools/win_cc.sh' --skip-fresh '' '$w/obj'"
fi
cc "$w/gen/fns.c" "$w/imports.c" "$w/api_wrappers.c" "$here/loader/win/win_rt.c" "$here/loader/win/darwin_win.c" "$here/loader/win/darwin_win_sys.c" "$here/loader/win/darwin_win_cxx.c" "$here/loader/win/darwin_win_libcxx.c" "$here/loader/win/darwin_win_cf.c" "$here/loader/win/plugins_win.c" "$here/loader/win/fmod_win.c"
MSYS_NO_PATHCONV=1 "$llvm/clang.exe" --target=x86_64-pc-windows-msvc -c "$(cygpath -w "$here/loader/win/win_call.S")" -o "$(cygpath -w "$w/obj/win_call.obj")"
objs=()
for o in "$w/obj"/*.obj; do objs+=("$(cygpath -w "$o")"); done
MSYS_NO_PATHCONV=1 "$llvm/lld-link.exe" /nologo /DLL /DEBUG "/PDB:$(cygpath -w "$w/MarbleKnights/GameAssembly.pdb")" "/OUT:$(cygpath -w "$w/GameAssembly.dll")" "${objs[@]}" \
  kernel32.lib user32.lib winmm.lib dbghelp.lib libucrt.lib libvcruntime.lib libcmt.lib
# the game's icon (tools/win_icon.py) as the launcher's resources
[ -f "$w/icon.ico" ] || python -I "$here/tools/win_icon.py"
MSYS_NO_PATHCONV=1 "$llvm/llvm-rc.exe" /nologo "/I$(cygpath -w "$w")" "/FO$(cygpath -w "$w/launcher.res")" "$(cygpath -w "$here/loader/win/launcher.rc")"
# /STACK: the main thread keeps guest stacks on its host stack (win_rt.c), so it needs room (reserved, committed as used)
MSYS_NO_PATHCONV=1 "$llvm/clang-cl.exe" /nologo /O2 "$(cygpath -w "$here/loader/win/launcher.c")" "/Fe$(cygpath -w "$w/launcher.exe")" "/Fo$(cygpath -w "$w/obj/launcher.o")" /link /SUBSYSTEM:WINDOWS /STACK:268435456 user32.lib "$(cygpath -w "$w/launcher.res")"
# for releases: MarbleKnights.exe without the game's icon (tools/prepare_win.py adds it from the
# player's IPA), and the launcher window (loader/win/mk_launcher.c)
MSYS_NO_PATHCONV=1 "$llvm/clang-cl.exe" /nologo /O2 "$(cygpath -w "$here/loader/win/launcher.c")" "/Fe$(cygpath -w "$w/launcher-plain.exe")" "/Fo$(cygpath -w "$w/obj/launcher-plain.o")" /link /SUBSYSTEM:WINDOWS /STACK:268435456 user32.lib
MSYS_NO_PATHCONV=1 "$llvm/llvm-rc.exe" /nologo "/I$(cygpath -w "$here/loader/win")" "/FO$(cygpath -w "$w/mk_launcher.res")" "$(cygpath -w "$here/loader/win/mk_launcher.rc")"
MSYS_NO_PATHCONV=1 "$llvm/clang-cl.exe" /nologo /O2 /W3 "$(cygpath -w "$here/loader/win/mk_launcher.c")" "/Fe$(cygpath -w "$w/MarbleKnightsLauncher.exe")" "/Fo$(cygpath -w "$w/obj/mk_launcher.o")" /link /SUBSYSTEM:WINDOWS user32.lib gdi32.lib comctl32.lib comdlg32.lib shell32.lib "$(cygpath -w "$w/mk_launcher.res")"
# mk_native.dll for the launcher's prepare step: our PVRTC decoder and LZ4 (built from the official
# lz4 1.10.0 source in work/third_party/lz4src, BSD-2-Clause; see THIRD_PARTY.md)
lz4src="$here/work/third_party/lz4src/lz4-1.10.0/lib"
if [ -f "$lz4src/lz4.c" ]; then
  MSYS_NO_PATHCONV=1 "$llvm/clang-cl.exe" /nologo /O2 /LD /DLZ4_DLL_EXPORT=1 "/I$(cygpath -w "$lz4src")" "$(cygpath -w "$here/tools/pvrtc_decode.c")" "$(cygpath -w "$lz4src/lz4.c")" "/Fe$(cygpath -w "$w/mk_native.dll")" "/Fo$(cygpath -w "$w/obj")\\"
fi
python -I "$here/tools/build_win.py" --gameassembly "$w/GameAssembly.dll"
mkdir -p "$w/MarbleKnights/MarbleKnights_Data/mk"
cp -u "$w/image/"* "$w/MarbleKnights/MarbleKnights_Data/mk/"
ls -la "$w/GameAssembly.dll"
